async page => {
  const API='http://127.0.0.1:18732', checks=[];
  const assert=(ok,message)=>{if(!ok)throw new Error(message);checks.push(message);};
  const rev=v=>({expected_turn:v.turn,revision:v.revision,world_version:v.world_version});
  const get=async path=>{const r=await page.request.get(API+path);if(!r.ok())throw new Error(await r.text());return r.json();};
  const send=async(method,path,data)=>{const r=await page.request[method](API+path,{data});if(!r.ok())throw new Error(await r.text());return r.json();};
  const schema=await get('/openapi.json');assert(schema.info.version==='3.3.0','bundled backend reports v3.3.0');
  assert(await page.evaluate(()=>location.protocol==='file:'&&typeof crypto.randomUUID==='function'),'AppImage file renderer supports command batches');
  assert(await page.evaluate(()=>typeof require==='undefined'&&typeof process==='undefined'),'renderer remains isolated from Node');
  const created=await send('post','/api/sessions',{scenario:'3.3.0 安装包验收 · 教学合成想定',mission_id:'AJ15-local-v1',persist_roles:false,use_adjudicator:true});
  const sid=created.session_id,path='/api/sessions/'+sid;await send('post',path+'/init');
  let view=await get(path+'/commands');
  await send('put',path+'/commands',{...rev(view),director:true,orders:view.units.map(u=>({unit_id:u.id,action:'hold'}))});
  await page.evaluate(id=>localStorage.setItem('gentactix-session',id),sid);await page.reload();
  await page.getByRole('tab',{name:/已保存战局/}).click();await page.locator('button').filter({hasText:sid}).first().click();
  await page.getByTestId('mission-panel').waitFor();
  await page.getByRole('button',{name:'红方 红方教学编组1',exact:true}).click();
  await page.getByTestId('command-panel').waitFor({state:'visible'});
  assert((await page.getByRole('combobox',{name:'单位名单（含无坐标单位）'}).inputValue()).length===32,'clicking marker opens unit command menu');
  await page.getByTestId('unit-action').selectOption('move');
  await page.getByRole('combobox',{name:'持续方式'}).selectOption('until_arrived');
  await page.getByRole('button',{name:'地图选目的地',exact:true}).click();
  const box=await page.getByRole('button',{name:'红方 红方教学编组1',exact:true}).boundingBox();if(!box)throw new Error('marker missing');
  await page.mouse.click(box.x+box.width+16,box.y+box.height+12);
  await page.getByTestId('command-panel').waitFor({state:'visible'});
  assert((await page.getByTestId('map-destination').innerText()).includes('目的地 '),'AppImage map supplies destination');
  const saved=page.waitForResponse(r=>r.url()===API+path+'/commands'&&r.request().method()==='PUT');
  await page.getByTestId('enqueue-order').click();assert((await saved).ok(),'move command confirms through frozen API');
  await page.getByRole('button',{name:'⏩ 下一轮推演',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[data-testid=mission-panel]')?.textContent.includes('1 / 4'));
  assert((await get(path)).turn_count===1,'AppImage executes one queued turn');
  assert((await get(path+'/unit-decisions')).total===6,'all six unit receipts survive packaged execution');
  await page.getByRole('button',{name:'本单位决策／执行回执',exact:true}).click();
  const records=page.locator('[aria-label=单位决策记录]');await records.waitFor();await records.scrollIntoViewIfNeeded();
  assert((await records.innerText()).includes('实际位置'),'packaged receipts display actual positions');
  await page.screenshot({path:'.cache/qa/release-v3.3.0/appimage-workspace.png'});
  const exported=await get(path+'/export');
  await page.getByRole('button',{name:'导入战局',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'导入已保存战局',exact:true});
  await dialog.getByLabel('战局 JSON 文件',{exact:true}).evaluate((input,json)=>{
    const transfer=new DataTransfer();transfer.items.add(new File([json],'campaign.json',{type:'application/json'}));
    input.files=transfer.files;input.dispatchEvent(new Event('change',{bubbles:true}));
  },JSON.stringify(exported));
  await dialog.getByTestId('import-preview').waitFor();
  assert(await dialog.getByRole('button',{name:'确认导入并打开',exact:true}).isDisabled(),'AppImage import preview protects existing game');
  await dialog.getByRole('button',{name:'取消',exact:true}).click();
  await page.getByRole('button',{name:'模型配置',exact:true}).click();
  await page.locator('#llm-model').waitFor();assert(await page.locator('#llm-model').isVisible(),'packaged model configuration opens');
  await page.getByRole('button',{name:'完成',exact:true}).click();
  return {passed:true,checks,session_id:sid};
}

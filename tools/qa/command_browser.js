async page => {
  const api = 'http://127.0.0.1:18870';
  const checks = [], errors = [];
  const assert = (ok, text) => { if (!ok) throw new Error(text); checks.push(text); };
  page.on('pageerror', e => errors.push(String(e)));
  const created = await page.request.post(api + '/api/sessions', {data:{scenario:'战棋界面隔离验收',mission_id:'AJ15-local-v1',persist_roles:false,use_adjudicator:true}});
  if (!created.ok()) throw new Error(await created.text());
  const sid = (await created.json()).session_id, path = api + '/api/sessions/' + sid;
  const initialized = await page.request.post(path + '/init');
  if (!initialized.ok()) throw new Error(await initialized.text());
  const initial = await initialized.json();
  await page.addInitScript(id => { window.gentactix = {backendUrl:'http://127.0.0.1:18870'}; localStorage.setItem('gentactix-session', id); }, sid);
  await page.setViewportSize({width:1530,height:980});
  await page.goto('http://127.0.0.1:18874', {waitUntil:'domcontentloaded'});
  await page.getByRole('tab', {name:/已保存战局/}).click();
  await page.locator('button').filter({hasText:sid}).first().click();
  await page.getByTestId('mission-panel').waitFor();
  await page.getByRole('button', {name:'红方 红方教学编组1',exact:true}).click();
  await page.getByTestId('command-panel').waitFor({state:'visible'});
  const unit = page.getByRole('combobox',{name:'单位名单（含无坐标单位）'});
  assert((await unit.inputValue()).length === 32, 'marker selects stable unit identity');
  await page.getByTestId('unit-action').selectOption('move');
  await page.getByRole('button',{name:'地图选目的地',exact:true}).click();
  await page.keyboard.press('Escape');
  assert(await page.getByTestId('command-panel').isVisible(), 'Escape returns to draft without executing');
  await page.waitForFunction(()=>document.activeElement?.textContent==='地图选目的地');
  assert(true, 'Escape restores keyboard focus to destination picker');
  await page.getByRole('combobox',{name:'持续方式'}).selectOption('until_arrived');
  await page.getByRole('button',{name:'地图选目的地',exact:true}).click();
  const box = await page.getByRole('button',{name:'红方 红方教学编组1',exact:true}).boundingBox();
  if (!box) throw new Error('marker missing');
  await page.mouse.click(box.x + box.width + 16, box.y + box.height + 12);
  await page.getByTestId('command-panel').waitFor({state:'visible'});
  assert((await page.getByTestId('map-destination').innerText()).includes('目的地 '), 'map supplies destination without coordinate typing');
  await page.screenshot({path:'.cache/qa/commands-browser/preview-wide.png'});
  await page.getByTestId('enqueue-order').click();
  await page.locator('[data-command-id]').waitFor();
  let data = await (await page.request.get(path + '/commands')).json();
  assert(data.orders.length === 1 && data.orders[0].duration === 'until_arrived', 'menu command saved as continuous task');
  const savedId = data.orders[0].id, selectedId = data.orders[0].unit_id;
  const before = await (await page.request.get(path)).json();
  assert(before.turn_count === 0 && JSON.stringify(before.war_state) === JSON.stringify(initial.war_state), 'confirmation does not advance or mutate world');
  await page.getByRole('button',{name:'⏩ 下一轮推演',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[data-testid=mission-panel]')?.textContent.includes('1 / 4'));
  await page.getByRole('button',{name:'本单位决策／执行回执',exact:true}).click();
  await page.locator('[aria-label=单位决策记录]').waitFor();
  const receiptText = await page.locator('[aria-label=单位决策记录]').innerText();
  assert(receiptText.includes('实际位置') && receiptText.includes('粮食：'), 'unit receipt shows actual positions and resource differences');
  const receipts = await (await page.request.get(path + '/unit-decisions?unit_id=' + selectedId)).json();
  assert(receipts.items[0].source === 'human' && receipts.items[0].dsh_event_ref === null, 'human receipt never pretends to be Agent reasoning');
  data = await (await page.request.get(path + '/commands')).json();
  if(data.orders.length) assert(data.orders[0].id === savedId, 'continuous task identity survives turn redraw');
  await page.screenshot({path:'.cache/qa/commands-browser/receipt-wide.png'});
  await page.locator('summary').filter({hasText:'自然语言：单位／全局控制'}).click();
  await page.getByRole('textbox',{name:'指挥内容'}).fill('前往选定位置，持续移动');
  await page.getByRole('button',{name:'DSH 解析为草稿',exact:true}).click();
  await page.getByText('待确认草稿',{exact:true}).waitFor();
  assert((await (await page.request.get(path)).json()).turn_count === 1, 'unit language yields unexecuted draft');
  await page.getByRole('button',{name:'确认草稿并入队',exact:true}).click();
  await page.getByText('待确认草稿',{exact:true}).waitFor({state:'hidden'});
  await page.getByRole('combobox',{name:'范围',exact:true}).selectOption('global');
  await page.getByRole('textbox',{name:'指挥内容'}).fill('全局待命，禁止主动射击');
  await page.getByRole('button',{name:'DSH 解析为草稿',exact:true}).click();
  await page.getByText('待确认草稿',{exact:true}).waitFor();
  await page.getByRole('button',{name:'确认草稿并入队',exact:true}).click();
  await page.getByText('待确认草稿',{exact:true}).waitFor({state:'hidden'});
  data = await (await page.request.get(path + '/commands')).json();
  assert(data.no_fire && data.orders.length === 3 && data.orders.every(o=>o.action==='hold'), 'global language shares command schema and hard restriction');
  await page.locator('[data-command-id]').first().getByRole('button',{name:'撤销',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('[data-command-id]').length===2);
  assert((await (await page.request.get(path)).json()).turn_count===1, 'queue cancellation consumes no battle time');
  data = await (await page.request.get(path + '/commands')).json();
  const external = await page.request.put(path + '/commands', {data:{expected_turn:data.turn,revision:data.revision,world_version:data.world_version,
    orders:data.orders.map(o=>({id:o.id,unit_id:o.unit_id,action:o.action,duration:o.duration})),intent:'外部修改后的意图',no_fire:true}});
  if(!external.ok()) throw new Error(await external.text());
  await page.getByTestId('unit-action').selectOption('hold');
  await page.getByTestId('enqueue-order').click();
  await page.getByRole('alert').filter({hasText:'版本已改变'}).waitFor();
  assert((await (await page.request.get(path + '/commands')).json()).orders.length===2, 'stale browser command cannot overwrite newer queue');
  await page.getByRole('button',{name:'刷新版本',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'版本已改变'}).waitFor({state:'hidden'});
  await page.getByTestId('enqueue-order').click();
  await page.waitForFunction(()=>document.querySelectorAll('[data-command-id]').length===3);
  assert((await (await page.request.get(path)).json()).turn_count===1, 'refresh and retry preserve draft and battle clock');
  await page.setViewportSize({width:390,height:844});
  await page.getByTestId('command-toggle').scrollIntoViewIfNeeded();
  await page.screenshot({path:'.cache/qa/commands-browser/workspace-narrow.png'});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2), 'narrow view has no horizontal overflow');
  const panel=await page.getByTestId('command-panel').boundingBox();
  assert(!!panel && panel.width<=390, 'narrow command sheet fits viewport');
  assert(errors.length===0, 'no uncaught browser exceptions');
  return {passed:true, session_id:sid, checks};
}
